import uuid


class Gрядка:
    """Грядка с возможностью мягкого удаления.

    Мягкое удаление: поле _удалена=True скрывает грядку из логического
    списка, но данные сохраняются в _восстановить для последующего
    восстановления.
    """

    def __init__(self, название, культура, площадь, дата_посадки):
        self.id = uuid.uuid4().hex
        self.название = название
        self.культура = культура
        self.площадь = площадь
        self.дата_посадки = дата_посадки
        self._удалена = False

    @property
    def активна(self):
        return not self._удалена

    def удалить(self):
        self._удалена = True

    def восстановить(self):
        self._удалена = False


class ЖурналГрядок:
    """Самодостаточный журнал грядок с поддержкой мягкого удаления."""

    def __init__(self):
        self._грядки = []

    def добавить(self, название, культура, площадь, дата_посадки):
        грядка = Gрядка(название, культура, площадь, дата_посадки)
        self._грядки.append(грядка)
        return грядка

    def активные(self):
        return [грядка for грядка in self._грядки if грядка.активна]

    def найти(self, название):
        for грядка in self.активные():
            if грядка.название == название:
                return грядка
        return None

    def удалить(self, название):
        грядка = self.найти(название)
        if грядка is not None:
            грядка.удалить()
            return True
        return False

    def восстановить(self, название):
        грядка = self.найти(название)
        if грядка is not None:
            грядка.восстановить()
            return True
        return False

    def все_грядки(self, включая_удаленные=False):
        if включая_удаленные:
            return list(self._грядки)
        return self.активные()

    def список_для_вывода(self):
        return list(self.активные())
