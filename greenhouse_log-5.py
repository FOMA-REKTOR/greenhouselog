# Project: GreenhouseLog
import datetime


class Gрядка:
    def __init__(self, название, культура, площадь, дата_посадки):
        self.название = название
        self.культура = культура
        self.площадь = площадь
        self.дата_посадки = дата_посадки


class Замер:
    def __init__(self, грядка, дата, температура, влажность, полев, удобрение):
        self.грядка = грядка
        self.дата = дата
        self.температура = температура
        self.влажность = влажность
        self.полев = полев
        self.удобрение = удобрение


class ЖурналТеплицы:
    def __init__(self):
        self.грядки = []
        self.замеры = []

    def добавить_грядку(self, грядка):
        self.грядки.append(грядка)

    def добавить_замер(self, замер):
        self.замеры.append(замер)

    def получить_замеры_для_грядки(self, название_грядки):
        return [замер for замер in self.замеры if замер.грядка.название == название_грядки]

    def проверить_целостность(self, название_грядки):
        замеры = self.получить_замеры_для_грядки(название_грядки)
        проблема = None
        for замер in замеры:
            if замер.грядка.название != название_грядки:
                проблема = "Связь разорвана: замер относится к другой грядке"
                break
        return проблема


if __name__ == "__main__":
    журнал = ЖурналТеплицы()
    грядка1 = Gрядка("Грядка 1", "Помидоры", 10, datetime.date(2023, 5, 1))
    грядка2 = Gрядка("Грядка 2", "Огурцы", 8, datetime.date(2023, 5, 2))
    журнал.добавить_грядку(грядка1)
    журнал.добавить_грядку(грядка2)
    журнал.добавить_замер(Замер(грядка1, datetime.date(2023, 5, 10), 25, 60, "Полив", "Удобрение"))
    журнал.добавить_замер(Замер(грядка1, datetime.date(2023, 5, 11), 26, 65, "Полив", "Удобрение"))
    журнал.добавить_замер(Замер(грядка2, datetime.date(2023, 5, 12), 24, 58, "Полив", "Удобрение"))
    замеры = журнал.получить_замеры_для_грядки("Грядка 1")
    print("Замеры для Грядки 1:", len(замеры))
    проблема = журнал.проверить_целостность("Грядка 1")
    print("Проблема с целостностью:", проблема)
